/**
 * Writes web/lib/routes.generated.ts: every Expo API route (src/app/api/**\/*+api.ts) as a
 * pattern plus a lazy import, so the Next.js web app serves the same handlers unchanged.
 * Run with `npm run web:routes` after adding or renaming an API route.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(__dirname, '..', 'src', 'app', 'api');
const files: string[] = [];
const walk = (dir: string) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f.endsWith('+api.ts') || f.endsWith('+api.tsx')) files.push(p);
  }
};
walk(root);

const rows = files.map((f) => {
  const rel = relative(root, f).replace(/\+api\.tsx?$/, '');
  const segs = rel.split('/').filter((s) => s !== 'index');
  const params: string[] = [];
  const re = segs
    .map((s) => {
      const m = s.match(/^\[(\.\.\.)?(.+)\]$/);
      if (!m) return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      params.push(m[2]);
      return m[1] ? '(.+)' : '([^/]+)';
    })
    .join('/');
  // Static segments win over dynamic ones: sort by dynamic count, then length.
  return { re: `^${re}$`, params, imp: relative(join(__dirname, '..', 'web', 'lib'), f).replace(/\.tsx?$/, ''), dyn: params.length, len: segs.length };
});
rows.sort((a, b) => a.dyn - b.dyn || b.len - a.len);

const out = `// Generated by scripts/web-routes.ts. Do not edit.
type Handler = (req: Request, params: Record<string, string>) => Promise<Response> | Response;
export type RouteModule = Partial<Record<'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE', Handler>>;
export const routes: { re: RegExp; params: string[]; load: () => Promise<RouteModule> }[] = [
${rows.map((r) => `  { re: /${r.re.replace(/\//g, '\\/')}/, params: ${JSON.stringify(r.params)}, load: () => import(${JSON.stringify(r.imp)}) as Promise<RouteModule> },`).join('\n')}
];
`;
writeFileSync(join(__dirname, '..', 'web', 'lib', 'routes.generated.ts'), out);
console.log(`${rows.length} routes`);
