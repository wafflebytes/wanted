/** Publish counts and fixed labels only. Raw evidence stays in gitignored .data. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { publicEvalReport, evalMarkdown, type PrivateEvalInput } from '../src/lib/eval-report';
const source = process.argv[2] ?? '.data/agent-llm-latest.json';
const input: PrivateEvalInput = existsSync(source) ? JSON.parse(readFileSync(source, 'utf8')) : {};
const report = publicEvalReport(input);
writeFileSync('src/ui/eval-report.generated.ts', `// Generated by npm run eval:report. Counts/allowlisted labels only.\nimport type { PublicEvalReport } from '../lib/eval-report';\nexport const EVAL_REPORT: PublicEvalReport = ${JSON.stringify(report, null, 2)};\n`);
writeFileSync('evals/report.md', evalMarkdown(report));
if (report.at) {
  const historyPath = 'evals/history.jsonl';
  const existing = existsSync(historyPath) ? readFileSync(historyPath, 'utf8').trim().split('\n').filter(Boolean) : [];
  const row = { at: report.at, suite: report.suite, gate: report.gate, passed: report.passed, cases: report.cases.length, noRejectedCalls: report.noRejectedCalls, httpRequests: report.httpRequests, qlooRequests: report.qlooRequests };
  if (!existing.some(s => { try { return JSON.parse(s).at === report.at; } catch { return false; } })) writeFileSync(historyPath, [...existing, JSON.stringify(row)].join('\n') + '\n');
}
console.log(JSON.stringify({ gate: report.gate, passed: report.passed, cases: report.cases.length, noRejectedCalls: report.noRejectedCalls, output: 'evals/report.md' }));
