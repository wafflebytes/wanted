/**
 * Builds Wanted's icon maps from MX Icons (src/ui/icons/names.ts lists the icons used).
 *
 * - src/ui/icons/mx.web.generated.ts: static imports of the MX Icons React components, so the
 *   web bundle carries only the icons Wanted uses.
 * - src/ui/icons/mx.native.generated.ts: the same icons rendered to SVG markup (MX Icons are DOM
 *   <svg> components, which React Native can't render), drawn with react-native-svg.
 *
 * Usage: npm run icons:build
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { createElement, type ComponentType } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ICON_NAMES } from '../src/ui/icons/names';

const VARIANTS = ['linear', 'bold'] as const;
const TAB_ICONS = ['map', 'tour', 'crowd', 'posters', 'inbox'] as const;
const ROOT = 'node_modules/mx-icons/dist/components';

type Variant = { variant: string; Component: ComponentType<{ size?: number; color?: string }> };

async function main() {
  const native: Record<string, Record<string, string>> = {};
  const webImports: string[] = [];
  const webMap: string[] = [];
  for (const [key, folder] of Object.entries(ICON_NAMES)) {
    if (!readdirSync(ROOT).includes(folder)) throw new Error(`MX Icons has no "${folder}" (for ${key})`);
    const mod = (await import(`mx-icons/components/${folder}`)) as { variants: Variant[] };
    native[key] = {};
    const ident = `i_${key}`;
    webImports.push(`import { variants as ${ident} } from 'mx-icons/components/${folder}';`);
    webMap.push(`  ${key}: pick(${ident}),`);
    for (const v of VARIANTS) {
      // A few icons (truck) ship no linear variant; outline is the same weight.
      const hit = mod.variants.find((x) => x.variant === v) ?? (v === 'linear' ? mod.variants.find((x) => x.variant === 'outline') : undefined);
      if (!hit) throw new Error(`MX Icons "${folder}" has no ${v} variant`);
      // Render at 24 with currentColor so the app can tint it at draw time.
      const svg = renderToStaticMarkup(createElement(hit.Component, { size: 24, color: 'currentColor' }))
        .replace(/ class=""/g, '')
        .replace(/ style="color:currentColor"/g, '');
      native[key][v] = svg;
    }
  }

  const header = `// Generated by scripts/build-icons.ts from MX Icons (MIT, https://mx-icons.vercel.app/). Do not edit.\n`;
  writeFileSync(
    'src/ui/icons/mx.web.generated.ts',
    `${header}import type { ComponentType } from 'react';\n${webImports.join('\n')}\n\ntype V = { variant: string; Component: ComponentType<{ size?: number | string; color?: string }> }[];\nconst pick = (v: V) => {\n  const by = Object.fromEntries(v.map((x) => [x.variant, x.Component]));\n  return { linear: by.linear ?? by.outline, bold: by.bold };\n};\n\nexport const MX = {\n${webMap.join('\n')}\n} as const;\n`,
  );
  writeFileSync('src/ui/icons/mx.native.generated.ts', `${header}export const MX_SVG: Record<string, Record<'linear' | 'bold', string>> = ${JSON.stringify(native, null, 1)};\n`);
  // iOS NativeTabs take image sources: render the tab icons as black template PNGs (25 pt @3x).
  mkdirSync('assets/icons', { recursive: true });
  for (const key of TAB_ICONS) {
    for (const v of VARIANTS) {
      const svg = native[key][v].replace(/currentColor/g, '#000').replace(/width="24" height="24"/, 'width="75" height="75"');
      await sharp(Buffer.from(svg)).png().toFile(`assets/icons/tab-${key}-${v}.png`);
    }
  }
  console.log(`Icons: ${Object.keys(ICON_NAMES).length} x ${VARIANTS.length} variants, ${TAB_ICONS.length} tab PNGs`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
