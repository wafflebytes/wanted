/**
 * Tiny inline placeholders for the big images, so a slow network shows the art's colors
 * instead of a black box while the full image loads (expo-image `placeholder`).
 *
 * Usage: npx tsx scripts/build-placeholders.ts
 */
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

const KEYS = ['cover', 'backdrop', 'poster-0', 'poster-1', 'poster-2', 'poster-3', 'gus-idle', 'gus-thinking', 'gus-proud', 'gus-unimpressed', 'gus-losing-it', 'gus-reading', 'gus-wave', 'maya-sticker', 'van'];

async function main() {
  const out: string[] = [];
  for (const k of KEYS) {
    const buf = await sharp(`assets/images/${k}.webp`).resize(24).webp({ quality: 40 }).toBuffer();
    out.push(`  '${k}': 'data:image/webp;base64,${buf.toString('base64')}',`);
  }
  writeFileSync(
    'src/ui/placeholders.generated.ts',
    `// Generated by scripts/build-placeholders.ts. Do not edit.\nexport const PLACEHOLDERS: Record<string, string> = {\n${out.join('\n')}\n};\n`,
  );
  console.log(`Placeholders: ${KEYS.length}`);
}
main();
