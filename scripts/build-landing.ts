/**
 * The landing map's data, baked from the seeded demo (Maya Ortiz) so the first screen draws
 * instantly with no network: Qloo heat binned into a halftone grid of the US, her tour route,
 * and the cities fans have signed.
 *
 * Usage: npx tsx scripts/build-landing.ts   (after `npm run seed`)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { cellToLatLng } from 'h3-js';
import { haversineKm } from '../src/lib/geo';

type MapShape = {
  sound: { entities: { name: string }[] };
  hexes: { h3: string; heat: number }[];
  metros: { id: string; name: string; state: string; lat: number; lon: number; rank: number | null }[];
  proof: { city: string; signatures: number; neighborhoods: { name: string; count: number }[] }[];
};
type PlanShape = { plan: { stops: { city: string; state: string; lat: number; lon: number }[]; total: number } };

const map: MapShape = JSON.parse(readFileSync('.data/shapes/artist_maya-ortiz_map.json', 'utf8'));
const { plan }: PlanShape = JSON.parse(readFileSync('.data/shapes/artist_maya-ortiz_plan.json', 'utf8'));

// Equirectangular, squeezed by cos(38°) so the lower 48 keep their familiar shape.
const K = Math.cos((38 * Math.PI) / 180);
const COLS = 64;
const X0 = -125 * K;
const Y0 = -49.5;
const CELL = (-66.5 * K - X0) / COLS;
const ROWS = Math.round((-24.5 - Y0) / CELL);
const project = (lat: number, lon: number): [number, number] => [(lon * K - X0) / CELL, (-lat - Y0) / CELL];
const r2 = (n: number) => Math.round(n * 100) / 100;

// Max heat per grid cell, then percentile rank so the ramp uses its whole range.
const cells = new Map<number, number>();
for (const h of map.hexes) {
  const [lat, lon] = cellToLatLng(h.h3);
  if (lon < -125 || lat < 24.5) continue;
  const [x, y] = project(lat, lon);
  const key = Math.floor(y) * COLS + Math.floor(x);
  cells.set(key, Math.max(cells.get(key) ?? 0, h.heat));
}
const sorted = [...cells.entries()].sort((a, b) => a[1] - b[1]);
const dots: number[] = [];
sorted.forEach(([key], i) => dots.push(key % COLS, Math.floor(key / COLS), r2(i / (sorted.length - 1))));

// The tour, and evenly spaced samples along it so a marker can ride the line.
const stops = plan.stops.map((s) => ({ city: s.city, state: s.state, xy: project(s.lat, s.lon).map(r2) as [number, number] }));
const segs = stops.slice(1).map((s, i) => Math.hypot(s.xy[0] - stops[i].xy[0], s.xy[1] - stops[i].xy[1]));
const length = segs.reduce((a, b) => a + b, 0);
const samples: number[] = [];
for (let n = 0; n <= 120; n++) {
  let d = (n / 120) * length;
  let i = 0;
  while (i < segs.length - 1 && d > segs[i]) d -= segs[i++];
  const t = segs[i] ? d / segs[i] : 0;
  const [a, b] = [stops[i].xy, stops[i + 1].xy];
  samples.push(r2(a[0] + (b[0] - a[0]) * t), r2(a[1] + (b[1] - a[1]) * t));
}
let km = 0;
for (let i = 1; i < plan.stops.length; i++) km += haversineKm(plan.stops[i - 1].lat, plan.stops[i - 1].lon, plan.stops[i].lat, plan.stops[i].lon);

// Cities with WANTED posters up, most signatures first.
const wanted = map.proof
  .map((p) => {
    const m = map.metros.find((x) => x.id === p.city)!;
    return { id: p.city, city: m.name, state: m.state, rank: m.rank, signatures: p.signatures, top: p.neighborhoods[0]?.name ?? null, xy: project(m.lat, m.lon).map(r2) as [number, number] };
  })
  .sort((a, b) => b.signatures - a.signatures);

const data = {
  cols: COLS,
  rows: ROWS,
  dots,
  route: { stops, samples, length: r2(length), km: Math.round(km), score: plan.total },
  wanted,
  sound: map.sound.entities.map((e) => e.name),
  metros: map.metros.length,
  hexes: map.hexes.length,
};
writeFileSync('src/ui/landing.generated.ts', `// Generated by scripts/build-landing.ts. Do not edit.\nexport const LANDING = ${JSON.stringify(data)} as const;\n`);
console.log(`Landing: ${COLS}x${ROWS} grid, ${sorted.length} dots, ${stops.length} stops (${Math.round(km)} km), ${wanted.length} wanted cities`);
