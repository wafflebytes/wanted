/** Bakes src/server/mcp-view.html into a TS string, so the server bundle carries Gus's Claude card. */
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('src/server/mcp-view.html', 'utf8');
writeFileSync(
  'src/server/mcp-view.gen.ts',
  `// Generated by scripts/build-mcp-view.mjs from mcp-view.html. Edit the HTML, then run npm run mcp:view.\nexport const MCP_VIEW_HTML = ${JSON.stringify(html)};\n`,
);
console.log('wrote src/server/mcp-view.gen.ts', html.length, 'chars');
